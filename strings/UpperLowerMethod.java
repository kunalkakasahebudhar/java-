/*
 * Method  : toUpperCase() / toLowerCase()
 * Use     : String che sagle characters uppercase ya lowercase madhe convert karto
 *           toUpperCase() - sagle letters CAPITAL karto
 *           toLowerCase() - sagle letters small karto
 * Syntax  : str.toUpperCase()
 *           str.toLowerCase()
 * Returns : String
 */
public class UpperLowerMethod {
    public static void main(String[] args) {
        String str = "Hello World";
        System.out.println("String: " + str);
        System.out.println("toUpperCase(): " + str.toUpperCase());
        System.out.println("toLowerCase(): " + str.toLowerCase());
    }
}
